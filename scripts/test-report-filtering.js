/**
 * Test script for role-based 360 report filtering
 *
 * This script tests:
 * 1. Existing report data structure
 * 2. Sentiment by relationship data
 * 3. Filtering logic
 */

const { createClient } = require('@supabase/supabase-js');
require('dotenv').config({ path: '.env.local' });

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
);

async function testReportFiltering() {
  console.log('🧪 Testing Role-Based Report Filtering\n');
  console.log('=' .repeat(60));

  // Step 1: Check existing reports
  console.log('\n📊 Step 1: Checking existing reports...\n');

  const { data: reports, error: reportsError } = await supabase
    .from('feedback_360_reports')
    .select(`
      id,
      survey_id,
      sentiment_by_relationship,
      generated_at,
      generated_by
    `);

  if (reportsError) {
    console.error('❌ Error fetching reports:', reportsError);
    return;
  }

  console.log(`✅ Found ${reports.length} reports in database\n`);

  if (reports.length === 0) {
    console.log('⚠️  No reports found. Please generate a report first.');
    return;
  }

  // Step 2: Analyze sentiment_by_relationship data
  console.log('=' .repeat(60));
  console.log('\n📈 Step 2: Analyzing sentiment_by_relationship structure...\n');

  reports.forEach((report, idx) => {
    console.log(`Report ${idx + 1}:`);
    console.log(`  ID: ${report.id}`);
    console.log(`  Survey ID: ${report.survey_id}`);
    console.log(`  Generated: ${new Date(report.generated_at).toLocaleString()}`);
    console.log(`  Generated by: ${report.generated_by}`);

    if (report.sentiment_by_relationship) {
      const sentiment = report.sentiment_by_relationship;
      console.log(`  Sentiment structure:`);
      console.log(`    Keys: ${Object.keys(sentiment).join(', ')}`);

      // Check if it has per-relationship data
      const hasRelationshipData =
        sentiment.manager !== undefined ||
        sentiment.peer !== undefined ||
        sentiment.direct_report !== undefined ||
        sentiment.cross_functional !== undefined;

      if (hasRelationshipData) {
        console.log(`    ✅ HAS relationship breakdown (will show to sponsors only)`);
        if (sentiment.manager) console.log(`      Manager: ${(sentiment.manager * 100).toFixed(1)}%`);
        if (sentiment.peer) console.log(`      Peer: ${(sentiment.peer * 100).toFixed(1)}%`);
        if (sentiment.direct_report) console.log(`      Direct Report: ${(sentiment.direct_report * 100).toFixed(1)}%`);
        if (sentiment.cross_functional) console.log(`      Cross-Functional: ${(sentiment.cross_functional * 100).toFixed(1)}%`);
      } else {
        console.log(`    ⚠️  NO relationship breakdown (only overall score)`);
      }

      if (sentiment.overall) {
        console.log(`    Overall: ${(sentiment.overall * 100).toFixed(1)}%`);
      }
    } else {
      console.log(`  ⚠️  No sentiment_by_relationship data`);
    }
    console.log('');
  });

  // Step 3: Get survey details for role testing
  console.log('=' .repeat(60));
  console.log('\n🔍 Step 3: Checking survey details for role testing...\n');

  const { data: surveys, error: surveysError } = await supabase
    .from('feedback_360_surveys')
    .select('id, survey_name, employee_id, created_by, status')
    .in('id', reports.map(r => r.survey_id));

  if (surveysError) {
    console.error('❌ Error fetching surveys:', surveysError);
    return;
  }

  surveys.forEach((survey, idx) => {
    console.log(`Survey ${idx + 1}:`);
    console.log(`  Name: ${survey.survey_name}`);
    console.log(`  Status: ${survey.status}`);
    console.log(`  Employee ID (subject): ${survey.employee_id}`);
    console.log(`  Created by (sponsor): ${survey.created_by}`);
    console.log('');
  });

  // Step 4: Test filtering logic
  console.log('=' .repeat(60));
  console.log('\n🧪 Step 4: Testing filtering logic...\n');

  const testReport = reports[0];
  const testSurvey = surveys.find(s => s.id === testReport.survey_id);

  if (!testSurvey) {
    console.log('⚠️  Could not find survey for report');
    return;
  }

  console.log('Test Scenario Setup:');
  console.log(`  Survey: ${testSurvey.survey_name}`);
  console.log(`  Sponsor (created_by): ${testSurvey.created_by}`);
  console.log(`  Subject (employee_id): ${testSurvey.employee_id}`);
  console.log(`  Status: ${testSurvey.status}\n`);

  // Simulate filtering
  const fullReport = testReport.sentiment_by_relationship;
  const filteredReport = {
    overall: fullReport.overall || 0
  };

  console.log('Sponsor/Admin View (FULL):');
  console.log(JSON.stringify(fullReport, null, 2));

  console.log('\nSubject View (FILTERED):');
  console.log(JSON.stringify(filteredReport, null, 2));

  // Step 5: Recommendations
  console.log('\n' + '=' .repeat(60));
  console.log('\n📋 Step 5: Testing Recommendations\n');

  console.log('To test the role-based filtering in your app:');
  console.log('');
  console.log('1️⃣  Test as SPONSOR (creator of survey):');
  console.log(`   - Login as user: ${testSurvey.created_by}`);
  console.log(`   - Navigate to 360 Feedback Dashboard`);
  console.log(`   - View report for: ${testSurvey.survey_name}`);
  console.log(`   - ✅ Should see "Sentiment by Relationship Type" section`);
  console.log('');

  console.log('2️⃣  Test as SUBJECT (employee being reviewed):');
  console.log(`   - Login as user: ${testSurvey.employee_id}`);
  console.log(`   - Navigate to 360 Feedback Dashboard`);
  console.log(`   - View report for: ${testSurvey.survey_name}`);
  if (testSurvey.status === 'finalized') {
    console.log(`   - ✅ Should see report WITHOUT relationship breakdown`);
    console.log(`   - ✅ Should only see overall sentiment score`);
  } else {
    console.log(`   - ❌ Should NOT be able to view (status: ${testSurvey.status})`);
    console.log(`   - ℹ️  Finalize the survey first to test subject view`);
  }
  console.log('');

  console.log('3️⃣  Test as ADMIN:');
  console.log(`   - Login as admin user`);
  console.log(`   - Navigate to 360 Feedback Dashboard`);
  console.log(`   - View any report`);
  console.log(`   - ✅ Should see full relationship breakdown`);
  console.log('');

  console.log('4️⃣  Test as UNAUTHORIZED USER:');
  console.log(`   - Login as user who is NOT sponsor, subject, or admin`);
  console.log(`   - Try to access: /api/360-generate-report?survey_id=${testSurvey.id}`);
  console.log(`   - ❌ Should get 403 Forbidden error`);
  console.log('');

  console.log('=' .repeat(60));
  console.log('\n✅ Test analysis complete!\n');
}

testReportFiltering().catch(console.error);
