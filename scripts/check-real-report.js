/**
 * Check the report for the actual survey that exists
 */

const { createClient } = require('@supabase/supabase-js');
require('dotenv').config();

const surveyId = '33297734-1580-4981-a487-afb8323d0ecd';

async function checkReport() {
  const supabase = createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL,
    process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
  );

  console.log('🔍 Checking report for survey:', surveyId);
  console.log('');

  // Get survey details
  const { data: survey, error: surveyError } = await supabase
    .from('feedback_360_surveys')
    .select('*')
    .eq('id', surveyId)
    .single();

  if (surveyError) {
    console.error('❌ Survey error:', surveyError);
    return;
  }

  console.log('📋 Survey Details:');
  console.log('   Name:', survey.survey_name);
  console.log('   Status:', survey.status);
  console.log('   Employee ID:', survey.employee_id);
  console.log('   Created by:', survey.created_by);
  console.log('   Finalized?:', survey.status === 'finalized' ? 'YES' : 'NO');
  console.log('');

  // Get report
  const { data: report, error: reportError } = await supabase
    .from('feedback_360_reports')
    .select('*')
    .eq('survey_id', surveyId)
    .single();

  if (reportError) {
    console.error('❌ Report error:', reportError);
    return;
  }

  console.log('📊 Report Details:');
  console.log('   Generated at:', report.generated_at);
  console.log('   Generated by:', report.generated_by);
  console.log('');

  console.log('🎯 Sentiment by Relationship:');
  console.log(JSON.stringify(report.sentiment_by_relationship, null, 2));
  console.log('');

  // Check format
  const hasRelationshipData =
    report.sentiment_by_relationship?.manager !== undefined ||
    report.sentiment_by_relationship?.peer !== undefined ||
    report.sentiment_by_relationship?.direct_report !== undefined ||
    report.sentiment_by_relationship?.cross_functional !== undefined;

  if (hasRelationshipData) {
    console.log('✅ REPORT HAS NEW FORMAT');
    console.log('   Contains per-relationship breakdown');
    console.log('   Filtering will be applied for subjects');
  } else {
    console.log('⚠️  REPORT HAS OLD FORMAT');
    console.log('   Only has overall score');
    console.log('   Need to regenerate with new analyzer');
  }
  console.log('');

  // Identify who should see what
  console.log('🔐 Access Control:');
  console.log('   Sponsor/Admin:', survey.created_by);
  console.log('   → Can see: FULL report with relationship breakdown');
  console.log('');
  console.log('   Subject:', survey.employee_id);
  console.log('   → Can see: FILTERED report (only overall score)');
  console.log('   → But ONLY if survey is finalized!');
}

checkReport().catch(console.error);
